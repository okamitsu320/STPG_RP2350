"""manual/getting-started.md as a new user follows it: the installed commands and a real browser (host only).

Needs the installed core, selenium, Firefox and geckodriver; without them it is
skipped, which is NOT RUN. HOME is temporary and the module starts with ``--no-device-run``: no port is listed or
opened. It says that the page's steps and labels work end to end; the rules behind them are tested elsewhere.
"""

from __future__ import annotations

import os
from pathlib import Path
import re
import subprocess
import sys
import time

import pytest

pytest.importorskip("selenium.webdriver")
from selenium.common.exceptions import NoSuchElementException, StaleElementReferenceException  # noqa: E402
from selenium.webdriver.common.by import By  # noqa: E402
from selenium.webdriver.support.ui import Select  # noqa: E402

from test_stpgview_browser import browser  # noqa: E402,F401 - module fixture

pytestmark = pytest.mark.stpg_host_only
HOME_KEY = "USERPROFILE" if sys.platform == "win32" else "HOME"


def command(module: str) -> list[str]:
    probe = subprocess.run([sys.executable, "-I", "-c", "import importlib.util; "
                            "print(importlib.util.find_spec('stpgview') is not None)"],
                           capture_output=True, text=True, timeout=30)
    if probe.returncode == 0 and probe.stdout.strip() == "False":
        pytest.skip("install the core into this Python before its isolated module-command test")
    assert probe.returncode == 0, probe.stderr
    return [sys.executable, "-I", "-m", module]


def manual_shot(driver, name: str, selector: str, *, size_for_panel: tuple[int, int] = (1280, 1200)) -> None:
    """Optional publisher capture of a UI panel from a neutral demo directory.

    The output folder must be selected explicitly. These are simulated public
    data; no screenshot is generated by a text/image model or a hardware run.
    """
    folder = os.environ.get("STPG_MANUAL_SHOTS")
    if folder:
        path = Path(folder)
        path.mkdir(parents=True, exist_ok=True)
        size = driver.get_window_size()
        driver.set_window_size(*size_for_panel)
        time.sleep(0.2)  # allow the real canvas to redraw for this viewport
        target = driver.find_element(By.CSS_SELECTOR, selector)
        driver.execute_script("arguments[0].scrollIntoView({block:'center'})", target)
        try:
            target.screenshot(str(path / name))
        finally:
            driver.set_window_size(size["width"], size["height"])


def until(predicate, what: str, timeout: float = 60.0):
    end = time.monotonic() + timeout
    while time.monotonic() < end:
        try:
            value = predicate()
        except (NoSuchElementException, StaleElementReferenceException):
            value = None
        if value:
            return value
        time.sleep(0.05)
    raise AssertionError(f"timed out waiting for {what}")


def act(step, what: str, timeout: float = 60.0) -> None:
    """Find and use an element in one go, again if its panel re-rendered in between (a stale element)."""

    def attempt():
        step()
        return True
    until(attempt, what, timeout)


def test_the_getting_started_page_works_as_written(browser, tmp_path):  # noqa: F811
    view, examples = command("stpgview"), command("stpgview.physical.patterns")
    home = tmp_path / "home"
    home.mkdir()
    environ = {k: v for k, v in os.environ.items()
               if k not in ("PYTHONPATH", "STPG_CONFIG_DIR", "XDG_CONFIG_HOME", "APPDATA")}
    environ[HOME_KEY] = str(home)
    environ["PATH"] = ""  # regression: no installed console script can be found through PATH
    subprocess.run([*view, "--help"], cwd=tmp_path, env=environ, capture_output=True, check=True, timeout=30)
    subprocess.run([*examples, "samples"], cwd=tmp_path, env=environ, capture_output=True, check=True, timeout=30)
    process = subprocess.Popen([*view, "--demo-device", "--no-device-run", "--no-browser",
                                "--config-dir", "./settings-check", "--results-dir", "./runs-check"], cwd=tmp_path, env=environ,
                               stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    try:
        lines = []
        for line in process.stdout:
            lines.append(line)
            if "Press Ctrl+C" in line:
                break
        assert any("settings folder:" in line for line in lines), lines
        driver = browser
        driver.get(re.search(r"http://\S+token=\S+", "".join(lines)).group(0))
        text = lambda element: driver.find_element(By.ID, element).text  # noqa: E731
        is_open = lambda dialog: driver.execute_script(  # noqa: E731
            "return document.getElementById(arguments[0]).open", dialog)

        # 4. Look at the pattern
        until(lambda: driver.find_element(By.ID, "openBtn").is_displayed(), "the Viewer")
        assert driver.find_element(By.ID, "openBtn").text == "Open…"
        driver.find_element(By.ID, "openBtn").click()
        driver.find_element(By.ID, "openPaths").send_keys(str(tmp_path / "samples" / "gui_tiny.stil"))
        driver.find_element(By.ID, "openSubmit").click()
        until(lambda: driver.find_element(By.ID, "runnerBtn").is_enabled(), "the open pattern")
        # Capture the waveform panel itself, at a viewport sized for two signals.
        manual_shot(driver, "viewer-simulated.png", "#waveHost", size_for_panel=(1280, 540))

        # 5. Build it
        assert driver.find_element(By.ID, "runnerBtn").text == "Build in Runner…"
        driver.find_element(By.ID, "runnerBtn").click()
        until(lambda: is_open("formDialog"), "the New project dialog")
        for name, value in (("wait_preset", "none"), ("completion", "hold")):
            act(lambda: Select(driver.find_element(By.CSS_SELECTOR, f"#formDialogBody select[name={name}]"))
                .select_by_value(value), name)
        assert driver.find_element(By.ID, "formDialogOk").text == "Create"
        driver.find_element(By.ID, "formDialogOk").click()
        until(lambda: not is_open("formDialog"), "the project")
        driver.find_element(By.ID, "rpBuild").click()
        until(lambda: "manifest" in text("rpBuildBody").lower(), "the build", 120)
        manual_shot(driver, "build-simulated.png", "#rpBuildBody")

        # 6. Run it
        act(lambda: Select(driver.find_element(By.CSS_SELECTOR, "#rpRunBody select[name=device]"))
            .select_by_value("simulated"), "the device list")
        until(lambda: driver.find_element(By.ID, "rpRun").is_enabled(), "Run…")
        assert driver.find_element(By.ID, "rpRun").text == "Run…"
        driver.find_element(By.ID, "rpRun").click()
        until(lambda: is_open("confirmRunDialog"), "the confirmation")
        assert "do not verify wiring or waveform timing" in text("confirmRunDialog")
        assert "contract M2" not in text("confirmRunDialog")
        manual_shot(driver, "run-confirm-simulated.png", "#confirmRunDialog")
        boxes = "#confirmRunAcks input[type=checkbox]"
        for index in range(len(driver.find_elements(By.CSS_SELECTOR, boxes))):
            act(lambda: driver.find_elements(By.CSS_SELECTOR, boxes)[index].is_selected()
                or driver.find_elements(By.CSS_SELECTOR, boxes)[index].click(), f"acknowledgement {index + 1}")
        until(lambda: all(b.is_selected() for b in driver.find_elements(By.CSS_SELECTOR, boxes))
              and driver.find_element(By.ID, "confirmRunStart").is_enabled(), "every acknowledgement")
        assert driver.find_element(By.ID, "confirmRunStart").text == "Start run"
        driver.find_element(By.ID, "confirmRunStart").click()
        until(lambda: "Overall" in text("rpRunBody"), "the result", 120)
        result = text("rpRunBody")
        assert "outcome" in result.lower() and "comparison" in result.lower() and "simulated" in result.lower()
        # what the README's tutorial tells the reader to expect
        assert "COMPLETED" in result and "NOT_APPLICABLE" in result and "SIMULATED — no hardware" in result
        manual_shot(driver, "run-simulated.png", "#rpRunBody > .form-grid:last-child", size_for_panel=(960, 1020))
    finally:
        process.terminate()
        process.wait(10)
    assert not (home / "stpg-work").exists() or list((home / "stpg-work").iterdir()) == []  # results stay in the project
